'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const app=read('static/app.js'),world=read('static/world-moderation.js');
const html=read('static/index.html'),css=read('static/world-moderation.css');
const server=read('world_chat.py'),pg=read('pg_storage.py');
new vm.Script(app,{filename:'app.js'});
new vm.Script(world,{filename:'world-moderation.js'});
assert(html.includes('/static/world-moderation.js?v=1.0'),'World UI must load');
assert(html.includes('/static/world-moderation.css?v=1.0'),'World layout must load');
assert(html.indexOf('world-moderation.js')>html.indexOf('app.js'),'World helpers load after core');
assert(html.includes('profile-separation.css'),'Dedicated profile styles must load');
assert(app.includes('function profileContent()'),'Separate profile page');
assert(app.includes('data-tab="profile"'),'Profile entry exists');
assert(app.includes('rail-profile-button'),'Profile button above Sign out');
assert(app.indexOf('rail-profile-button')<app.indexOf('rail-logout'),'Profile must be above Sign out');
const settings=app.slice(app.indexOf('function settingsContent(){'),app.indexOf('function supportInApp(){'));
assert(!settings.includes('profileSettings()'),'Profile is no longer inside Settings');
assert(settings.includes('settings-pin')&&settings.includes('settings-password'),'Security tools preserved');
assert(settings.includes('worldPenaltyCard'),'Warnings visible in settings');
assert(world.includes('function worldPage()')&&world.includes('function worldPenaltyCard()'));
assert(world.includes('function adminWorldContent()')&&world.includes('function adminReportsContent()'));
assert(world.includes("post('/api/reports'"),'Member reporting action is connected');
assert(world.includes("post('/api/admin/world/mute'"),'Admin manual mute action exists');
assert(world.includes("post('/api/admin/world/config'"),'Admin schedule action exists');
assert(world.includes("post('/api/admin/world/reset'"),'Admin reset action exists');
assert(world.includes("post('/api/admin/reports/")||world.includes("post('/api/admin/reports/'+"),'Admin report decision exists');
assert(world.includes('data-world-countdown'),'Countdown widget exists');
assert(server.includes('SPAM_THRESHOLD = 5')&&server.includes('SPAM_WINDOW = 3'));
assert(server.includes('WARNINGS_PER_PENALTY = 3'));
assert(server.includes('RESET_AFTER = 30 * 86400'));
assert(server.includes('ACCOUNT_LOCK_SECONDS = 15*86400'));
assert(server.includes('MUTE_DURATIONS = (12*3600, 86400, 3*86400, 7*86400)'));
assert(server.includes('class WorldConfig(BaseModel)'));
assert(server.includes("verify_admin_stepup(request,admin,body.admin_password,body.admin_pin)"));
assert(server.includes('UPDATE world_penalties SET window_count=window_count'),'Persistent row lock protects rate rule');
assert(server.includes('scope:Literal'), 'Evidence scope is validated');
assert(server.includes('status:Literal'), 'Report state must be validated');
assert(pg.includes("'world_messages', 'user_reports'"),'PostgreSQL inserts get generated IDs');
assert(css.includes('.world-live-shell')&&css.includes('.world-report-card'));
assert(css.includes('@media(max-width:650px)'),'Mobile World Chat works');
assert(!/localStorage|sessionStorage|document.cookie/.test(world),'No sensitive messages or reports stored in browser storage');
console.log('World and profile UI wiring OK: guarded rooms, moderation, reports, responsive layout.');
