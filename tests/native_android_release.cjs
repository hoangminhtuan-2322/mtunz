'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const crypto=require('node:crypto');
const {execFileSync}=require('node:child_process');

const app=require('../mobile/app.json').expo;
const config=fs.readFileSync('mobile/app.config.js','utf8');
const code=fs.readFileSync('mobile/App.js','utf8');
const chat=fs.readFileSync('mobile/src/Messenger.js','utf8');
const api=fs.readFileSync('mobile/src/client.js','utf8');
const workflow=fs.readFileSync('.github/workflows/android-apk.yml','utf8');
const sign=fs.readFileSync('mobile/tools/configure_fixed_release_signing.cjs','utf8');
const smoke=fs.readFileSync('mobile/tools/smoke_native_android.sh','utf8');
const signed=require('../android-web/release-signing.json');

assert.equal(app.name,'mtunz');
assert.equal(app.version,'1.1.1');
assert.equal(app.android.package,'com.mtunz.web');
assert.equal(app.android.versionCode,4);
assert.equal(app.icon,'./assets/icon.png');
assert.equal(app.android.softwareKeyboardLayoutMode,'resize');
const original=fs.readFileSync('android-web/app/src/main/res/drawable-nodpi/mtunz_icon.png');
const native=fs.readFileSync('mobile/assets/icon.png');
assert(original.equals(native),'Native icon must exactly equal original 1.0.0 logo bytes');
assert.equal(execFileSync('git',['hash-object','mobile/assets/icon.png'],{encoding:'utf8'}).trim(),
  '282a6971e38d51ce570b094e07d5624663bbedbb');
assert.equal(signed.package_name,'com.mtunz.web');
assert.equal(signed.release_cert_sha256,
  '80:6A:14:7A:41:42:20:3F:05:EA:D8:C5:76:3D:4C:D5:59:C4:D6:CC:B9:EC:FF:02:BA:72:8D:59:AA:1A:8F:7B');

assert(/SecureStore/.test(api)&&/wsUrl/.test(api),'Native app must use authenticated REST + WebSocket');
assert(/<Messenger/.test(code)&&/AdminDashboard/.test(code),'Use native screens, not browser.');
assert(/new WebSocket\(wsUrl\(\)/.test(chat),'Native chat must connect realtime');
assert(/FlatList/.test(chat),'Native message list must be a React Native list');
assert(/uploadAttachment/.test(chat),'Native chat should support files and media');
assert(!/react-native-webview|TrustedWebActivity|CustomTabs/.test(code+chat),'Native UI must not embed website');

assert(workflow.includes('npx expo prebuild --platform android'),'Android native project generated by Expo');
assert(workflow.includes('assets/index.android.bundle'),'Standalone JS bundle must be in APK');
assert(workflow.includes('com.mtunz.web'),'Native APK must keep installed package');
assert(workflow.includes('versionCode=\'4\''),'Must increment Android version code');
assert(workflow.includes('mtunz-NATIVE-1.1.0-RELEASE-fixed-key'));
assert(workflow.includes('configure_preview_package.cjs'));
assert(workflow.includes('mtunz-NATIVE-SIDEBYSIDE-PREVIEW-debug'));
assert(workflow.includes('EXPECTED_PACKAGE=com.mtunz.web.preview'));
const preview=fs.readFileSync('mobile/tools/configure_preview_package.cjs','utf8');
assert(preview.includes("applicationIdSuffix '.preview'"));
assert(preview.includes('mtunz Preview'));
assert(workflow.includes('github.event_name == \'workflow_dispatch\' && inputs.sign_release'),'Real signing must be explicit');
assert(workflow.includes('verify_release_artifact.py'),'Require pinned permanent cert');
assert(workflow.includes('REQUIRE_NATIVE_PUSH'),'Signed release must require native background push configuration');
assert(sign.includes('signingConfig signingConfigs.mtunzFixedRelease'),'Generated Gradle release must use owner key');
assert(smoke.includes('adb shell pidof "$PACKAGE"'),'Must prove native process remains alive');
assert(smoke.includes('adb logcat -d -b crash'),'Must check for crashes');
assert(!workflow.includes('mtunz-web-android-RELEASE-new-fixed-key'),'Do not confuse TWA APK with native APK');
console.log('mtunz TRUE native identity/logo, signed upgrade, realtime and no-browser release gates passed.');
